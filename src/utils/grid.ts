import { COORD_PACK_BIAS, COORD_PACK_MULTIPLIER } from '../constants/world_chunk.constants.ts';

/**
 * Converts 2D grid coordinates to a 1D flat array index.
 * @param x The grid x coordinate.
 * @param y The grid y coordinate.
 * @param width The width of the grid/map.
 * @returns The 1D flat index.
 */
export function coordToIndex(x: number, y: number, width: number): number {
  return y * width + x;
}

/**
 * Packs signed integer `(x, y)` coordinates (+/- 33,554,431 per axis) into a single safe JS integer
 * without string allocations or bounds-width coupling.
 *
 * @param x World X coordinate.
 * @param y World Y coordinate.
 * @returns Packed numeric world coordinate key.
 */
export function packWorldCoord(x: number, y: number): number {
  return (y + COORD_PACK_BIAS) * COORD_PACK_MULTIPLIER + (x + COORD_PACK_BIAS);
}

/**
 * Unpacks a numeric coordinate key generated by {@link packWorldCoord} back into signed `(x, y)`.
 *
 * @param key Packed world coordinate key.
 * @returns Object containing signed `x` and `y` coordinates.
 */
export function unpackWorldCoord(key: number): { readonly x: number; readonly y: number } {
  const adjustedX = key % COORD_PACK_MULTIPLIER;
  const x = adjustedX - COORD_PACK_BIAS;
  const y = Math.floor(key / COORD_PACK_MULTIPLIER) - COORD_PACK_BIAS;
  return { x, y };
}

/**
 * Maps a signed world coordinate axis value to its enclosing chunk coordinate using floored division.
 *
 * @param coord World coordinate value.
 * @param chunkSize Chunk edge dimension in tiles.
 * @returns Signed chunk axis coordinate.
 */
export function worldToChunkCoord(coord: number, chunkSize: number): number {
  return Math.floor(coord / chunkSize);
}

/**
 * Computes the non-negative local cell offset `[0, chunkSize)` inside the enclosing chunk.
 *
 * @param coord World coordinate value.
 * @param chunkSize Chunk edge dimension in tiles.
 * @returns Local offset within `[0, chunkSize)`.
 */
export function worldToLocalCoord(coord: number, chunkSize: number): number {
  return ((coord % chunkSize) + chunkSize) % chunkSize;
}

/**
 * Computes the flat SoA TypedArray cell index `[0, chunkSize * chunkSize)` for `(x, y)`.
 *
 * @param x World X coordinate.
 * @param y World Y coordinate.
 * @param chunkSize Chunk edge dimension in tiles.
 * @returns Flat local cell index inside the enclosing chunk.
 */
export function worldToLocalIndex(x: number, y: number, chunkSize: number): number {
  const lx = worldToLocalCoord(x, chunkSize);
  const ly = worldToLocalCoord(y, chunkSize);
  return ly * chunkSize + lx;
}

/**
 * Formats a stable string key identifying a chunk coordinate `(cx, cy, cz)`.
 *
 * @param cx Chunk X coordinate.
 * @param cy Chunk Y coordinate.
 * @param cz Chunk Z coordinate (defaults to 0).
 * @returns Formatted chunk key string.
 */
export function formatChunkKey(cx: number, cy: number, cz = 0): string {
  return `${cx},${cy},${cz}`;
}

/**
 * Checks if a coordinate is within the boundaries of the grid.
 * @param x The grid x coordinate.
 * @param y The grid y coordinate.
 * @param width The width of the grid/map.
 * @param height The height of the grid/map.
 * @returns True if the coordinate is in bounds.
 */
export function isInBounds(x: number, y: number, width: number, height: number): boolean {
  return x >= 0 && x < width && y >= 0 && y < height;
}

/**
 * Returns an array of points representing a line from (x0, y0) to (x1, y1)
 * using Bresenham's line algorithm.
 */
export function getBresenhamLine(x0: number, y0: number, x1: number, y1: number): Array<{ x: number; y: number }> {
  const points = [];
  const dx = Math.abs(x1 - x0);
  const dy = Math.abs(y1 - y0);
  const sx = x0 < x1 ? 1 : -1;
  const sy = y0 < y1 ? 1 : -1;
  let err = dx - dy;

  // eslint-disable-next-line no-constant-condition
  while (true) {
    points.push({ x: x0, y: y0 });
    if (x0 === x1 && y0 === y1) break;
    const e2 = 2 * err;
    if (e2 > -dy) {
      err -= dy;
      x0 += sx;
    }
    if (e2 < dx) {
      err += dx;
      y0 += sy;
    }
  }
  return points;
}
